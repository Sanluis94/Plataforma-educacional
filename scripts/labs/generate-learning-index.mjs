import { readFile, writeFile, readdir } from 'node:fs/promises';
const root = new URL('../../', import.meta.url);
const source = await readFile(new URL('src/modules/core/constants/masterLabsCatalog.ts', root), 'utf8');
const catalog = JSON.parse(source.match(/export const MASTER_LABS_CATALOG: CatalogLabItem\[\] = (\[[\s\S]*?\]);/)[1]);
const fields = ['id', 'title', 'academicLevel', 'subject', 'topic', 'objective', 'icon'];
const index = catalog.map(item => Object.fromEntries(fields.map(key => [key, item[key]])));
const directory = new URL('src/modules/core/content/', root);
const packs = {};
for (const path of (await readdir(directory)).filter(path => path.endsWith('.json')).sort()) {
  for (const id of Object.keys(JSON.parse(await readFile(new URL(path, directory), 'utf8')))) {
    if (packs[id]) throw new Error(`Conteúdo duplicado: ${id}`);
    packs[id] = `./${path}`;
  }
}
const outputs = [
  ['src/modules/core/constants/learningCatalogIndex.ts', `// Generated by scripts/labs/generate-learning-index.mjs.\nimport type { LearningLevel } from './learningLevels';\nexport const LEARNING_CATALOG_INDEX: {id:string;title:string;academicLevel:LearningLevel;subject:string;topic:string;objective:string;icon:string}[] = ${JSON.stringify(index)};\n`],
  ['src/modules/core/content/labPackIndex.ts', `// Generated by scripts/labs/generate-learning-index.mjs.\nexport const LAB_PACK_INDEX: Record<string, string> = ${JSON.stringify(packs)};\n`],
];
for (const [path, expected] of outputs) {
  if (process.argv.includes('--check')) {
    if (await readFile(new URL(path, root), 'utf8') !== expected) throw new Error(`${path}: regenere o índice do catálogo.`);
  } else await writeFile(new URL(path, root), expected);
}
console.log(`Índice leve: ${index.length} itens; conteúdo: ${Object.keys(packs).length} laboratórios.`);

import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { initializeApp, deleteApp } from 'firebase/app';
import { connectAuthEmulator, getAuth, createUserWithEmailAndPassword, signInWithEmailAndPassword, signOut, inMemoryPersistence, setPersistence } from 'firebase/auth';
import { connectFirestoreEmulator, getFirestore, doc, setDoc, getDocFromServer, terminate } from 'firebase/firestore';
import { app, auth, db } from '../../src/modules/core/services/firebaseConfig.ts';
import { saveSubmission } from '../../src/modules/data/repositories/submissionRepository.ts';
import { saveExamAttempt } from '../../src/modules/data/repositories/examRepository.ts';
import { completeStudentLabProgress } from '../../src/modules/data/repositories/studentRepository.ts';
import { completeStudentLab } from '../../src/modules/core/services/studentLabService.ts';
import { getLiveClassReport } from '../../src/modules/data/repositories/reportRepository.ts';
import { offlineSyncService } from '../../src/modules/core/services/offlineSyncService.ts';
import { initializeApp as initializeAdminApp } from 'firebase-admin/app';
import { getFirestore as getAdminFirestore } from 'firebase-admin/firestore';

assert.equal(app.options.projectId, 'demo-kortex');
assert.equal(process.env.FIRESTORE_EMULATOR_HOST, '127.0.0.1:8080');
const storage = new Map();
globalThis.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value), removeItem: key => storage.delete(key) };
const timeout = setTimeout(() => { console.error('Verificação ETL do emulador excedeu 90 segundos.'); process.exit(1); }, 90_000);
const suffix = crypto.randomUUID();
const password = 'FicticioLocal123!';
const teacherEmail = `professor-${suffix}@example.test`;
const studentEmail = `aluno-${suffix}@example.test`;
const now = new Date().toISOString();
const checks = [];
const auxiliaries = [];
async function learner(name) {
  const auxiliaryApp = initializeApp({ apiKey: 'demo-kortex-api-key', authDomain: 'demo-kortex.firebaseapp.com', projectId: 'demo-kortex', appId: 'demo-kortex-etl' }, `${name}-${suffix}`);
  const auxiliaryAuth = getAuth(auxiliaryApp), auxiliaryDb = getFirestore(auxiliaryApp);
  connectAuthEmulator(auxiliaryAuth, 'http://127.0.0.1:9099', { disableWarnings: true });
  connectFirestoreEmulator(auxiliaryDb, '127.0.0.1', 8080);
  await setPersistence(auxiliaryAuth, inMemoryPersistence);
  const email = name === 'aluno' ? studentEmail : `${name}-${suffix}@example.test`;
  const { user } = await createUserWithEmailAndPassword(auxiliaryAuth, email, password);
  await setDoc(doc(auxiliaryDb, 'users', user.uid), { name: name === 'aluno' ? 'Aluno fictício' : 'Sem entrega', email, role: 'estudante', createdAt: now });
  auxiliaries.push({ app: auxiliaryApp, db: auxiliaryDb });
  return user.uid;
}
try {
  await setPersistence(auth, inMemoryPersistence);
  const { user: teacher } = await createUserWithEmailAndPassword(auth, teacherEmail, password);
  await setDoc(doc(db, 'users', teacher.uid), { name: 'Professora fictícia', email: teacherEmail, role: 'professor', createdAt: now });
  const studentId = await learner('aluno');
  const absentId = await learner('sem-entrega');
  const classId = `class-${suffix}`, otherClass = `other-${suffix}`;
  const classData = { name: 'Turma de verificação ETL', professorId: teacher.uid, professorName: 'Professora fictícia', studentIds: [studentId, absentId], studentsCount: 2, createdAt: now, updatedAt: now };
  const fixtureApp=initializeAdminApp({projectId:'demo-kortex'},`etl-fixture-${suffix}`);
  const fixtureStore=getAdminFirestore(fixtureApp);
  // Only emulator fixture setup bypasses rules. Application deliveries below
  // still run through the actual authenticated client and deployed rules file.
  await fixtureStore.doc(`classes/${classId}`).set(classData);
  await fixtureStore.doc(`classes/${otherClass}`).set({ ...classData, studentIds: [studentId], studentsCount: 1 });
  await fixtureStore.terminate();await fixtureApp.delete();
  const activityId = `activity-${suffix}`, examId = `exam-${suffix}`, planId = `plan-${suffix}`;
  await setDoc(doc(db, 'activities', activityId), { title: 'Atividade medida', type: 'quiz', config: {}, professorId: teacher.uid, classId, status: 'published', createdAt: now });
  await setDoc(doc(db, 'activities', `other-${activityId}`), { title: 'Outra turma', type: 'quiz', config: {}, professorId: teacher.uid, classId: otherClass, status: 'published', createdAt: now });
  await setDoc(doc(db, 'exams', examId), { professorId: teacher.uid, titulo: 'Prova de verificação', disciplina: 'Ciências', turmaId: classId, status: 'Aberta', pesoTotal: 2, criadoEm: now, questoes: [{ enunciado: 'O que observou?', tema: 'Observação', nivelDificuldade: 'Fácil', valorPeso: 2, justificativa: 'Caso fictício', opcoes: [{ texto: 'Resposta correta', isCorreta: true }, { texto: 'Resposta incorreta', isCorreta: false }] }] });
  await setDoc(doc(db, 'lesson_plans', planId), { professorId: teacher.uid, turmaId: classId, periodo: '1º Bimestre', topico: 'Comparação', metodologia: 'Investigar', laboratorioAssociadoId: 'fund1_mat_01', laboratorioTitulo: 'Balança', status: 'em_andamento', criadoEm: now });
  await signOut(auth);
  await signInWithEmailAndPassword(auth, studentEmail, password);
  offlineSyncService.setOnline(false);
  offlineSyncService.setCurrentStudent(studentId);
  const evidence = { schemaVersion: 1, source: 'activity', sessionId: `session-${suffix}`, stage: 'assessment', activeSeconds: 75, questions: [{ questionId: 'q1', question: 'Qual evidência?', selectedOption: 0, selectedText: 'Resposta real', correct: true }], reflection: 'Conclusão preservada' };
  const payload = { activityId, activityTitle: 'Atividade medida', classId, studentId, studentName: 'Aluno fictício', score: 80, status: 'completed', submittedAt: now, evidence };
  const first = await saveSubmission(payload);
  const retry = await saveSubmission(payload);
  assert.equal(retry.id, first.id);
  assert.equal((await getDocFromServer(doc(db, 'submissions', first.id))).data().evidence.reflection, 'Conclusão preservada');
  checks.push('Envio real e reenvio com o mesmo ID confirmados sem duplicar a entrega');
  const reward = await completeStudentLabProgress(studentId, activityId, 80);
  const repeatedReward = await completeStudentLabProgress(studentId, activityId, 80);
  assert.equal(reward.progress.xp, repeatedReward.progress.xp);
  assert.equal(repeatedReward.alreadyCompleted, true);
  checks.push('Recompensa transacional única no progresso canônico');
  const next = { ...payload, score: 0, submittedAt: new Date().toISOString(), evidence: { ...evidence, sessionId: `retake-${suffix}`, questions: [{ questionId: 'q1', question: 'Qual evidência?', selectedOption: 1, selectedText: 'Resposta incorreta', correct: false }] } };
  const queued = await offlineSyncService.deliver({ kind: 'submission', studentId, rewardId: activityId, submission: next });
  assert.equal(queued.queued, true);
  const foreign = { ...payload, studentId: absentId, evidence: { ...evidence, sessionId: `foreign-${suffix}` } };
  offlineSyncService.enqueueSubmission({ kind: 'submission', studentId: absentId, submission: foreign });
  offlineSyncService.setOnline(true);
  await offlineSyncService.syncOutbox();
  assert.equal(offlineSyncService.getPendingSubmissions(studentId).length, 0);
  assert.equal(offlineSyncService.getPendingSubmissions(absentId).length, 1);
  await assert.rejects(saveSubmission(foreign));
  checks.push('Fila confirma a escrita real e preserva itens de outra conta; regras negam envio em nome de outro aluno');
  await saveExamAttempt({ examId, examTitle: 'Prova de verificação', turmaId: classId, alunoId: studentId, alunoNome: 'Aluno fictício', pontuacaoObtida: 1, pontuacaoMaxima: 2, porcentagemAproveitamento: 50, classificacao: 'Regular', respostas: [{ questaoIndex: 0, opcaoEscolhidaIndex: 1, acertou: false, pontosObtidos: 1 }], dataEnvio: new Date().toISOString(), evidence: { ...evidence, source: 'exam', sessionId: `exam-attempt-${suffix}` } });
  await completeStudentLab(studentId, 'estudante', { id: 'fund1_mat_01', title: 'Balança', classId, lessonPlanId: planId }, 50, { ...evidence, source: 'lab', sessionId: `lab-${suffix}`, observations: [{ scenarioId: 'cenario1', scenarioLabel: 'Comparação', observed: true, hypothesis: 'Minha previsão' }] }, 'Aluno fictício');
  offlineSyncService.setCurrentStudent(null);
  await signOut(auth);
  await signInWithEmailAndPassword(auth, teacherEmail, password);
  const report = await getLiveClassReport(classId);
  assert.equal(report.activitiesCount, 3);
  assert.equal(report.expectedCompletions, 6);
  assert.equal(report.completedActivitiesCount, 3);
  assert.equal(report.completionRate, 50);
  assert.equal(report.quality.retries, 1);
  const student = report.students.find(item => item.studentId === studentId);
  assert.equal(student.records.length, 4);
  assert.equal(student.status, 'precisa_apoio');
  assert.equal(student.records.find(item => item.source === 'lab').evidence.observations[0].hypothesis, 'Minha previsão');
  assert.equal(report.students.find(item => item.studentId === absentId).lastActive, null);
  assert.equal(report.students.find(item => item.studentId === absentId).averageScore, null);
  const isolated = await getLiveClassReport(otherClass);
  assert.equal(isolated.completedActivitiesCount, 0);
  assert.equal(isolated.averageScore, null);
  checks.push('Professor recebe atividade, avaliação e laboratório do plano; zero e ausência distintos; turmas isoladas');
  const directory = new URL('../../.local/learning-emulator/', import.meta.url);
  await mkdir(directory, { recursive: true });
  await writeFile(new URL('result.json', directory), JSON.stringify({ status: 'passed', project: 'demo-kortex', checkedAt: new Date().toISOString(), checks, completedActivities: report.completedActivitiesCount, expectedCompletions: report.expectedCompletions, productionAccessed: false }, null, 2));
  console.log(JSON.stringify({ status: 'passed', project: 'demo-kortex', checks }));
} finally {
  offlineSyncService.setOnline(false);
  clearTimeout(timeout);
  for (const auxiliary of auxiliaries) { await terminate(auxiliary.db); await deleteApp(auxiliary.app); }
  await terminate(db);
  await deleteApp(app);
}
